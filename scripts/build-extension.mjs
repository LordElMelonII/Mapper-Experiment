#!/usr/bin/env node
// scripts/build-extension.mjs — D8: one-file ESM extension bundle.
//
// 1. `ng build -c extension` (Angular CLI application builder; entry src/st/entry.ts)
// 2. esbuild merge pass: dist/travel-map-explorer/browser/*.js → ONE self-contained
//    ESM at dist/extension/index.js (no bare-specifier imports left), minified
// 3. copy manifest.json; emit dist/extension/style.css (build product, or a
//    placeholder when the build emits no css)
// 4. report sizes; fail over the 1.5 MB min+gz budget (D8)
//
// Zero dependency except esbuild (D52) and node: builtins.

import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { extname, join, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';

const ROOT = resolve(import.meta.dirname, '..');
const BROWSER = join(ROOT, 'dist', 'travel-map-explorer', 'browser');
const EXTENSION = join(ROOT, 'dist', 'extension');
const BUDGET = 1.5 * 1024 * 1024; // D8: 1.5 MB min+gz
const DEFAULT_CSS = '/* Travel & Map Explorer — no global styles emitted by the build yet */\n';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild');

function runNgBuild() {
  const ng = require.resolve('@angular/cli/bin/ng.js');
  // spawn node directly: no npx / shell resolution variance on win32
  const result = spawnSync(process.execPath, [ng, 'build', '-c', 'extension'], {
    stdio: 'inherit',
    cwd: ROOT,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`ng build failed (exit code ${result.status})`);
}

/** Entry strategy: with chunks, main*.js is enough — the CLI already bundled all
 *  reachable modules into it and esbuild inlines dynamic imports when bundling. */
function collectEntrypoints() {
  if (!statSync(BROWSER).isDirectory()) {
    throw new Error(`build output missing: ${BROWSER}`);
  }
  const jsFiles = readdirSync(BROWSER, { withFileTypes: true })
    .filter((d) => d.isFile() && extname(d.name) === '.js')
    .map((d) => join(BROWSER, d.name));
  if (jsFiles.length === 0) throw new Error(`no .js files produced in ${BROWSER}`);

  const main = jsFiles.find((f) => f.endsWith('main.js') || /(^|[\\/])main[^\\/]*\.js$/.test(f));
  if (main) {
    const others = jsFiles.filter((f) => f !== main);
    if (others.length > 0) {
      // never bundle the entry alone and lose chunks: import them too (side-effect order: main first)
      const stub = join(ROOT, 'dist', '.merge-entry.mjs');
      const specs = [main, ...others]
        .map((f) => `import ${JSON.stringify(f.replaceAll('\\\\', '/'))};`)
        .join('\n');
      writeFileSync(stub, `// generated by build-extension.mjs — chunk merge stub\n${specs}\n`);
      return { entry: stub, stub };
    }
    return { entry: main, stub: undefined };
  }
  throw new Error('no main*.js in build output; chunk layout not recognised — STOP and inspect');
}

/** Bundles everything into one ESM file. */
async function mergeInto(indexMod, stubPath) {
  mkdirSync(EXTENSION, { recursive: true });
  await esbuild.build({
    entryPoints: [indexMod],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    outfile: join(EXTENSION, 'index.js'),
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'warning',
  });
  if (stubPath) rmSync(stubPath, { force: true });
}

/** The bundle must not leave bare-specifier imports behind (host: native dynamic import). */
function assertSelfContained() {
  const text = readFileSync(join(EXTENSION, 'index.js'), 'utf8');
  const specs = new Set();
  for (const m of text.matchAll(/^\s*import\s[^;]*?from\s*['"]([^'"]+)['"]/gm)) specs.add(m[1]);
  for (const m of text.matchAll(/^\s*import\s*['"]([^'"]+)['"]/gm)) specs.add(m[1]);
  for (const m of text.matchAll(/import\(\s*['"]([^'"]+)['"]\s*\)/g)) specs.add(m[1]);
  const bare = [...specs].filter((s) => !s.startsWith('.') && !s.startsWith('node:'));
  if (bare.length > 0) {
    throw new Error(`dist/extension/index.js still imports: ${bare.join(', ')}`);
  }
}

function emitCss() {
  const css = readdirSync(BROWSER, { withFileTypes: true })
    .filter((d) => d.isFile() && d.name.endsWith('.css'))
    .map((d) => d.name);
  if (css.length === 1) {
    copyFileSync(join(BROWSER, css[0]), join(EXTENSION, 'style.css'));
    return css[0];
  }
  // 0 or >1 css files: deterministic placeholder so the manifest's css field stays valid
  writeFileSync(join(EXTENSION, 'style.css'), DEFAULT_CSS);
  return null;
}

async function main() {
  runNgBuild();
  const { entry, stub } = collectEntrypoints();
  await mergeInto(entry, stub);
  assertSelfContained();

  const indexJs = join(EXTENSION, 'index.js');
  const raw = readFileSync(indexJs).length;
  const gz = gzipSync(readFileSync(indexJs), { level: 9 }).length;
  if (gz > BUDGET) {
    throw new Error(`bundle budget (D8) exceeded: ${(gz / 1024).toFixed(1)} KB gz > ${(BUDGET / 1024).toFixed(0)} KB`);
  }

  copyFileSync(join(ROOT, 'manifest.json'), join(EXTENSION, 'manifest.json'));
  const cssSource = emitCss();

  console.log(`[build-extension] dist/extension/index.js  raw ${(raw / 1024).toFixed(1)} KB · min+gz ${(gz / 1024).toFixed(1)} KB (budget ${(BUDGET / 1024).toFixed(0)} KB)`);
  console.log(`[build-extension] dist/extension/manifest.json + style.css (${cssSource ? `from ${cssSource}` : 'placeholder'})`);
}

main().catch((err) => {
  console.error('[build-extension] FAILED:', err instanceof Error ? err.message : err);
  process.exit(1);
});
